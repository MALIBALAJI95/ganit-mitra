HUNDREDS = {
    100: "शंभर", 200: "दोनशे", 300: "तीनशे", 400: "चारशे", 500: "पाचशे",
    600: "सहाशे", 700: "सातशे", 800: "आठशे", 900: "नऊशे"
}

def number_to_marathi(n: int) -> str:
    if n in MARATHI_NUMS_0_100:
        return MARATHI_NUMS_0_100[n]
    
    parts = []
    
    # Thousands (1000 - 9999)
    if n >= 1000:
        thousands = n // 1000
        n %= 1000
        parts.append(f"{MARATHI_NUMS_0_100[thousands]} हजार")
    
    # Hundreds (100 - 900)
    if n >= 100:
        hundred_digit = (n // 100) * 100
        n %= 100
        parts.append(HUNDREDS[hundred_digit])
    
    # Remaining 1 - 99
    if n > 0:
        parts.append(MARATHI_NUMS_0_100[n])
        
    return " ".join(parts)

# Verify 0 to 10,000 generate valid non-empty Marathi words
